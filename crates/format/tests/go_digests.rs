//! Digests the Go implementation computed (format.Digest, Go 1.27) for
//! manifests with fields this reader doesn't know, numbers in every form,
//! repeated keys, lone surrogates and bytes that aren't UTF-8: the Rust
//! implementation must agree, or files already published wouldn't open.

use odi_format::{digest, digest_string, Chunk, Entry, Kind};

#[test]
fn same_digests_as_go() {
    let entries = vec![
        Entry { path: "app".into(), kind: Kind::Dir, mode: 0o755, size: 0, chunks: vec![], target: String::new() },
        Entry {
            path: "app/a".into(),
            kind: Kind::File,
            mode: 0o644,
            size: 3,
            chunks: vec![Chunk { hash: "ab".into(), offset: 64, length: 7, size: 3 }],
            target: String::new(),
        },
        Entry { path: "app/l".into(), kind: Kind::Symlink, mode: 0, size: 0, chunks: vec![], target: "a".into() },
    ];
    let cases: [(&[u8], &str); 3] = [
        (b"\x7b\x22\x6f\x64\x69\x22\x3a\x22\x30\x2e\x31\x22\x2c\x22\x6e\x61\x6d\x65\x22\x3a\x22\x74\x22\x2c\x22\x78\x22\x3a\x5b\x31\x65\x33\x2c\x31\x45\x2b\x33\x2c\x2d\x30\x2e\x30\x2c\x31\x2e\x35\x30\x2c\x31\x32\x33\x34\x35\x36\x37\x38\x39\x30\x31\x32\x33\x34\x35\x36\x37\x38\x39\x30\x31\x32\x33\x5d\x2c\x22\x79\x22\x3a\x7b\x22\x62\x22\x3a\x31\x2c\x22\x61\x22\x3a\x32\x2c\x22\x62\x22\x3a\x33\x7d\x2c\x22\x7a\x22\x3a\x22\x5c\x75\x64\x38\x30\x30\x20\x5c\x75\x64\x38\x33\x64\x5c\x75\x64\x65\x30\x30\x20\x5c\x75\x30\x30\x65\x39\x20\x3c\x26\x3e\x20\x5c\x75\x32\x30\x32\x38\x20\xe2\x80\xa8\x20\xf0\x9f\x98\x80\x22\x7d", "sha256:e1a74f587bac0e83a631d83b4b9db22c4d004a7316239d61efb982abc482bdc5"),
        (b"\x7b\x22\x6f\x64\x69\x22\x3a\x22\x30\x2e\x31\x22\x2c\x22\x6e\x61\x6d\x65\x22\x3a\x22\x74\x22\x2c\x22\x62\x61\x64\x22\x3a\x22\x61\xff\x62\xc3\x22\x7d", "sha256:dd2161b947e2e3ef84c5883314357d5556f25827b274dd2aaad624711827af7d"),
        (b"\x7b\x22\x6f\x64\x69\x22\x3a\x22\x30\x2e\x31\x22\x2c\x22\x6e\x61\x6d\x65\x22\x3a\x22\x74\x22\x2c\x22\x6e\x65\x73\x74\x65\x64\x22\x3a\x7b\x22\x6b\x22\x3a\x5b\x7b\x22\x7a\x22\x3a\x6e\x75\x6c\x6c\x2c\x22\x61\x22\x3a\x74\x72\x75\x65\x7d\x5d\x7d\x2c\x20\x22\x65\x73\x63\x22\x3a\x22\x5c\x2f\x5c\x62\x5c\x66\x22\x7d", "sha256:227ae0fcf794cdbf832450416c260fd542438efd9f1284ce3eb9451f355c4987"),
    ];
    // (As exact bytes: the first holds escapes, a surrogate pair, a lone half
    // and raw U+2028; the second, bytes that aren't UTF-8.)
    for (m, want) in cases {
        assert_eq!(digest_string(&digest(m, &entries).unwrap()), want, "{}", String::from_utf8_lossy(m));
    }
}
